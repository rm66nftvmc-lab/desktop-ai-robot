"""Render the original black-background atlas poses as one looping GIF.

This is a source-atlas preview only. The current firmware preview, including
the photo background and selected four-frame state animations, is generated by
build_screen_assets.py.

Run:  .\\.venv\\Scripts\\python.exe scripts\\render_faces_animation.py
"""

from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build_faces as faces  # noqa: E402

FRAMES = 6
SCREEN = (240, 320)
HOLD_MS = 120
LABEL_COLOUR = (255, 210, 90)


def screen_frame(atlas: Image.Image, row: int, column: int) -> Image.Image:
    """One frame, placed on the screen exactly as lcdDrawFace() places it."""
    face = faces.compose(faces.cell_frame(atlas, row, column), faces.BACKGROUND)
    canvas = Image.new("RGB", SCREEN, faces.BACKGROUND)
    canvas.paste(face, (0, (SCREEN[1] - faces.FACE_PIXELS) // 2))
    return canvas


def main() -> int:
    root = Path(__file__).resolve().parents[1]
    atlas = faces.load_atlas(faces.default_cache(), allow_download=False)

    frames: list[Image.Image] = []
    for name, row, column, _purpose in faces.FACES:
        added = 0
        for candidate in range(FRAMES):
            frame = screen_frame(atlas, row, candidate)
            if frame.getbbox() is None:
                continue  # this column of the atlas row is empty
            ImageDraw.Draw(frame).text((5, 5), f"{name}  r{row}c{candidate}",
                                       fill=LABEL_COLOUR)
            frames.append(frame)
            added += 1
        print(f"  {name:<8} r{row}c{column}  {added} 帧")

    if not frames:
        print("没有可用帧")
        return 1

    out = root / "faces-atlas-animation.gif"
    frames[0].save(out, save_all=True, append_images=frames[1:],
                   duration=HOLD_MS, loop=0, optimize=False)
    print(f"\n{len(frames)} 帧 -> {out} ({out.stat().st_size / 1024:.0f} KB)")
    print(f"旋转 ROTATE_CCW = {faces.ROTATE_CCW}"
          f"{'（逆时针 90°，头顶朝左）' if faces.ROTATE_CCW == 90 else ''}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
