"""Generate the sphere texture; motion and expressions run locally on ESP32.

Character reference: sam70361/aora-bot, Emotion Ball Community License.
See voice-device/assets/qiuqiu/LICENSE and NOTICE.md (non-commercial only).
"""
from pathlib import Path
import math
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SIZE = 192


def build():
    image = Image.new('RGB', (SIZE, SIZE))
    pixels = []
    for y in range(SIZE):
        for x in range(SIZE):
            dx, dy = (x - 95.5) / 79, (y - 95.5) / 79
            r2 = dx * dx + dy * dy
            glow = math.exp(-((x - 96)**2 + (y - 121)**2) / 10000)
            glow *= min(1, min(x, y, SIZE-1-x, SIZE-1-y) / 20)
            bg = (int(8 + 7 * glow), int(8 + 3 * glow), int(24 + 15 * glow))
            if r2 <= 1:
                z = math.sqrt(1 - r2)
                light = max(0, -.35 * dx - .48 * dy + .8 * z)
                shade = .64 + .36 * light
                color = tuple(min(255, int(c * shade)) for c in (249, 239, 212))
                edge = min(1, (1 - math.sqrt(r2)) * 79)
                color = tuple(int(a * edge + b * (1-edge)) for a, b in zip(color, bg))
            else:
                color = bg
            pixels.append(color)
    image.putdata(pixels)
    out = ROOT / 'voice-device/assets/qiuqiu'
    image.save(out / 'texture.png')
    values = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3) for r,g,b in pixels]
    lines = ['// Generated by scripts/build_qiuqiu.py; see assets/qiuqiu/LICENSE.',
             '#pragma once', '#include <pgmspace.h>',
             'static const uint16_t QIUQIU_TEXTURE[192*192] PROGMEM = {']
    lines += [','.join(f'0x{v:04x}' for v in values[i:i+24])+',' for i in range(0,len(values),24)]
    lines += ['};', '']
    (ROOT / 'voice-device/src/qiuqiu_assets.h').write_text('\n'.join(lines), encoding='utf-8')


if __name__ == '__main__':
    build()
